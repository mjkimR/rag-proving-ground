from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field


class EvalCase(BaseModel):
    """
    Represents a single evaluation test case.
    Can be loaded with just question and ground_truth, and populated with answer and contexts after execution.
    """

    question: str = Field(..., description="The user query or question")
    ground_truth: str | None = Field(default=None, description="The expected correct answer")
    answer: str | None = Field(default=None, description="The actual output/answer generated by the RAG pipeline")
    contexts: list[str] | None = Field(default=None, description="The list of retrieved contexts/chunks")
    metadata: dict[str, Any] | None = Field(
        default=None, description="Additional context-specific metadata (e.g. document source, category)"
    )


class EvalDataset(BaseModel):
    """
    A collection of evaluation cases.
    """

    name: str = Field(default="default_eval_dataset", description="Name of the dataset")
    cases: list[EvalCase] = Field(default_factory=list, description="List of evaluation cases")


class MetricScore(BaseModel):
    """
    Score details for a single metric on a single test case.
    """

    name: str = Field(..., description="Name of the metric (e.g., faithfulness)")
    score: float = Field(..., description="Score value (typically between 0.0 and 1.0)")
    reason: str | None = Field(
        default=None, description="The reasoning behind the score (if provided by the evaluator)"
    )


class EvalCaseResult(BaseModel):
    """
    The result of running and evaluating a single test case.
    """

    case: EvalCase = Field(
        ..., description="The evaluated test case containing question, ground_truth, answer, contexts"
    )
    metrics: list[MetricScore] = Field(default_factory=list, description="Calculated metric scores")
    latency_sec: float | None = Field(default=None, description="Time taken to run the RAG pipeline for this case")
    success: bool = Field(default=True, description="Whether the run and evaluation succeeded")
    error_message: str | None = Field(default=None, description="Error message if the evaluation failed")


class EvalRunResult(BaseModel):
    """
    The summarized result of a complete evaluation run.
    """

    dataset_name: str = Field(..., description="Name of the dataset evaluated")
    results: list[EvalCaseResult] = Field(..., description="List of individual case results")
    summary: dict[str, float] = Field(..., description="Aggregated metric averages (e.g. {'faithfulness': 0.85})")
    timestamp: datetime = Field(default_factory=datetime.utcnow, description="Timestamp of the evaluation run")
    total_latency_sec: float = Field(..., description="Total execution time for the evaluation run")
